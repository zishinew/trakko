import type { ProducerTools, Contact, StoreEvent, MailJob, OrderItem } from './tools';
export type Deliverable = 'mp3' | 'wav' | 'stems';
export type FileKind = Deliverable | 'preview' | 'cover' | 'avatar' | 'banner';
export type Store = {
  id: string;
  owner_id: string;
  username: string;
  display_name: string;
  bio: string;
  avatar_url: string;
  banner_url: string;
  accent: string;
  theme: 'dark' | 'light';
  instagram: string;
  youtube: string;
  website: string;
  published: boolean;
  created_at: string;
};
export type Beat = {
  release_at?: string | null;
  free_download?: boolean;
  free_download_terms?: string;
  id: string;
  store_id: string;
  title: string;
  bpm: number;
  musical_key: string;
  tags: string[];
  description: string;
  cover_url: string;
  preview_url: string;
  published: boolean;
  created_at: string;
};
export type License = {
  id: string;
  store_id: string;
  beat_id: string | null;
  name: string;
  price_cents: number;
  terms: string;
  active: boolean;
  deliverables: Deliverable[];
};
export type BeatFile = {
  id: string;
  beat_id: string;
  store_id: string;
  kind: FileKind;
  path: string;
  name: string;
  size: number;
};
export type Order = {
  items?: OrderItem[];
  subtotal_cents?: number;
  discount_cents?: number;
  promotion_code?: string;
  bundle_name?: string;
  receipt_ciphertext?: string;
  source?: string;
  id: string;
  store_id: string;
  beat_id: string;
  license_id: string;
  customer_email: string;
  amount_cents: number;
  fee_cents: number;
  earnings_cents: number;
  currency: string;
  beat_title: string;
  producer_name: string;
  license_name: string;
  license_terms: string;
  deliverables: Deliverable[];
  files: Pick<BeatFile, 'id' | 'kind' | 'path' | 'name'>[];
  status: 'pending' | 'paid' | 'refunded';
  fulfillment_status: 'pending' | 'ready';
  stripe_session_id: string | null;
  stripe_payment_id: string | null;
  token_hash: string;
  created_at: string;
  paid_at: string | null;
};
export type StripeAccount = {
  store_id: string;
  account_id: string;
  charges_enabled: boolean;
  payouts_enabled: boolean;
  details_submitted: boolean;
};
export type Workspace = {
  as_of?: string;
  tools?: ProducerTools;
  contacts?: Contact[];
  events?: StoreEvent[];
  mail_jobs?: MailJob[];
  store: Store;
  beats: Beat[];
  licenses: License[];
  files: BeatFile[];
  orders: Order[];
  plays: { beat_id: string; created_at: string }[];
  play_counts?: { all: number; week: number; month: number };
  stripe: StripeAccount | null;
};
export type PublicCatalog = Pick<Workspace, 'store' | 'beats' | 'licenses' | 'tools'>;
